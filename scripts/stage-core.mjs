import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { sha256, integrity, verifyCore } from "./core-files.mjs";
const root = fileURLToPath(new URL("..", import.meta.url));
const manifest = JSON.parse(await readFile(join(root,"package.json"),"utf8"));
const lock = JSON.parse(await readFile(join(root,"package-lock.json"),"utf8"));
const candidate = JSON.parse(await readFile(join(root,".core-input","candidate.json"),"utf8"));
const reference = manifest.devDependencies["@ding112/moneypal-core"];
if (reference !== `file:.core-input/${candidate.filename}` || candidate.name !== "@ding112/moneypal-core" || candidate.version !== "1.0.0-migration.0") throw new Error("核心输入引用无效。");
const bytes = await readFile(join(root,".core-input",candidate.filename));
if (sha256(bytes) !== candidate.sha256 || integrity(bytes) !== candidate.integrity || lock.packages["node_modules/@ding112/moneypal-core"]?.integrity !== candidate.integrity) throw new Error("核心候选或锁文件摘要不匹配。");
const source = join(root,"node_modules","@ding112","moneypal-core");
const record = await verifyCore(source,candidate.sourceRecordSha256);
if (record.version !== candidate.version || record.sourceCommit !== candidate.sourceCommit) throw new Error("核心来源与候选不一致。");
const target = join(root,"src","core");
await rm(target,{recursive:true,force:true}); await mkdir(dirname(target),{recursive:true});
await cp(source,target,{recursive:true});
await writeFile(join(root,"src","core-provenance.json"),`${JSON.stringify({schemaVersion:1,name:record.name,version:record.version,sourceCommit:record.sourceCommit,tarballSha256:candidate.sha256,integrity:candidate.integrity,sourceRecordSha256:candidate.sourceRecordSha256,files:record.files},null,2)}\n`);
await verifyCore(target,candidate.sourceRecordSha256);
console.log(`核心已准备：${record.name}@${record.version}`);
